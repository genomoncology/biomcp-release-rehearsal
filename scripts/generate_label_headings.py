"""Generate SPL headings from FDA's druglabel.yaml, supplied as a local file.

Download https://raw.githubusercontent.com/FDA/open.fda.gov/bd1232aa1f0cb8efba7334afb419f4e331803b23/static/fields/druglabel.yaml
and pass its path. Only top-level arrays of strings are SPL section fields;
scalar identity/revision fields and the openfda/meta objects are metadata.
"""
import hashlib
import re
import sys
from pathlib import Path

schema = Path(sys.argv[1]).read_bytes()
blocks = re.findall(r'^  ([a-z_]+):\n(.*?)(?=^  [a-z_]+:|\Z)',
                    schema.decode(), re.M | re.S)
headings = [name for name, body in blocks
            if re.search(r'^    type: array$', body, re.M)
            and re.search(r'^      type: string$', body, re.M)]
if not headings or len(headings) != len(set(headings)):
    raise ValueError('invalid publisher schema')
output = Path(__file__).resolve().parents[1] / 'crates/biomcp-types/src/drug/label_headings.rs'
output.write_text(
    '//! Published SPL section fields; generated by scripts/generate_label_headings.py.\n'
    '// Source: https://raw.githubusercontent.com/FDA/open.fda.gov/bd1232aa1f0cb8efba7334afb419f4e331803b23/static/fields/druglabel.yaml\n'
    f'// SHA256: {hashlib.sha256(schema).hexdigest()}\n'
    '/// All top-level string-array SPL sections in the publisher schema.\n'
    f'pub const OPENFDA_LABEL_HEADINGS: [&str; {len(headings)}] = [\n'
    + ''.join(f'    "{name}",\n' for name in headings) + '];\n')
