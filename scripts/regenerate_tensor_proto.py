"""Reproduce the private protobuf message closure from checked, pinned local inputs."""
import argparse
import hashlib
import re
from pathlib import Path
import subprocess
import tempfile

PIN = "55943112b83439e0c2512110f1ae607d4b5b492a"
INPUTS = {
    "alphagenome/protos/v1/dna_model_service.proto": "d487d76600e7e25413780e8dfb63c0129ca8449e3b3baee10ef6d3caf0927f86",
    "alphagenome/protos/v1/dna_model.proto": "cce623263fe102712673d79ed861a07388b9841ef8bf310edc9f0d9f1154f6d9",
    "alphagenome/protos/tensor.proto": "07779023b2868377cbfc3c2ce96cd266ae425a0a1116aea755691c263d6238f7",
}
NAME = "google.gdm.gdmscience.alphagenome.v1main.rs"
HEADER = (
    "// Generated by the pinned prost generator. Do not edit.\n"
    "// Copyright 2024 Google LLC. Apache-2.0; see ../../../proto/LICENSE.\n"
)


def split_generated(text):
    """Split only between top-level generated Rust items to retain the file ceiling."""
    text = re.sub(r"(?m)^(\s*)pub ", r"\1pub(crate) ", text)
    items, current, depth = [], [], 0
    for line in text.splitlines(keepends=True):
        current.append(line)
        code = line.split("//", 1)[0]
        depth += code.count("{") - code.count("}")
        if depth == 0 and code.strip() == "}":
            items.append("".join(current))
            current = []
    if "".join(current).strip():
        raise ValueError("unrecognized generated Rust tail")
    parts, group = [], ""
    for item in items:
        if len(item.splitlines()) > 298:
            raise ValueError("generated item exceeds file ceiling")
        if len((group + item).splitlines()) > 298:
            parts.append(group)
            group = ""
        group += item
    if group:
        parts.append(group)
    files = {f"part{index:03}.rs": HEADER + part for index, part in enumerate(parts)}
    files["mod.rs"] = HEADER + "".join(f'include!("{name}");\n' for name in files)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    proto = root / "crates/biomcp-fetch/proto"
    for path, digest in INPUTS.items():
        if hashlib.sha256((proto / path).read_bytes()).hexdigest() != digest:
            raise ValueError(f"pinned proto mismatch: {PIN}/{path}")
    target = root / "crates/biomcp-adapters/src/alphagenome/generated"
    with tempfile.TemporaryDirectory(prefix="tensor-proto-") as temporary:
        subprocess.run([
            "cargo", "run", "--locked", "--manifest-path",
            str(root / "tools/tensor-proto-generator/Cargo.toml"), "--", str(proto), temporary,
        ], check=True, cwd=root)
        expected = split_generated((Path(temporary) / NAME).read_text())
    if args.check:
        actual = {path.name: path.read_text() for path in target.glob("*.rs")}
        if actual != expected:
            raise ValueError("committed protobuf output differs from pinned regeneration")
    else:
        target.mkdir(parents=True, exist_ok=True)
        for path in target.glob("*.rs"):
            path.unlink()
        for name, text in expected.items():
            (target / name).write_text(text)
    print(f"Pinned protobuf closure verified: {PIN}")


if __name__ == "__main__":
    main()
